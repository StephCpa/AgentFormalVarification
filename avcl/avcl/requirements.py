import re


def merge_requirements(*groups):
    """Keep public identifiers only, including user-defined contract IDs."""
    return tuple(sorted({value for group in groups for value in group
                         if type(value) is str and
                         re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.-]{0,127}", value)}))


