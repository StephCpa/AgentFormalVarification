CODE_REQUIREMENTS = {}
for _ids, _codes in _GROUPS:
    for _code in _codes.split():
        if _code in CODE_REQUIREMENTS:
            raise RuntimeError("Duplicate diagnostic classification: " + _code)
        CODE_REQUIREMENTS[_code] = _ids


def requirements_for(code):
    return CODE_REQUIREMENTS.get(code, ())
